// Asia/Shanghai 日期（UTC+8）
function todayShanghai() {
  const now = new Date();
  const sh = new Date(now.getTime() + 8 * 3600 * 1000);
  return sh.toISOString().slice(0, 10);
}

function parseArgs(argv) {
  const args = { batch: 8, dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--batch") args.batch = parseInt(argv[i + 1], 10) || 8;
    if (argv[i] === "--dry-run") args.dryRun = true;
  }
  return args;
}

function yamlArr(arr) {
  return `[${arr.map((x) => `"${x}"`).join(", ")}]`;
}

function renderFaq(seed) {
  return seed.faqItems
    .map((f) => `  - question: ${f.question}\n    answer: ${f.answer}`)
    .join("\n");
}

function renderRelated(seed) {
  const base = RELATED_BY_CATEGORY[seed.category] || [];
  const extra = seed.extraRelated || [];
  const all = [...new Set([...base, ...extra])];
  return all.map((p) => `  - ${p}`).join("\n");
}

function renderArticle(seed, today) {
  const fm = [
    "---",
    `title: ${seed.title}`,
    "type: FAQ",
    `category: ${seed.category}`,
    `keywords: ${yamlArr(seed.keywords)}`,
    `excerpt: ${seed.excerpt}`,
    `description: ${seed.description}`,
    "authorName: AooBee 编辑部",
    `publishedAt: ${today}`,
    `updatedAt: ${today}`,
    "faqItems:",
    renderFaq(seed),
    "related:",
    renderRelated(seed),
    "---",
    "",
    `# ${seed.title}`,
    "",
    seed.sections.map((s) => s.trim()).join("\n\n"),
    "",
    CONTACT_BLOCK,
    "",
  ].join("\n");
  return fm;
}

function main() {
  const { batch, dryRun } = parseArgs(process.argv.slice(2));
  if (!fs.existsSync(FAQ_DIR)) {
    console.error(`未找到 FAQ 目录: ${FAQ_DIR}`);
    process.exit(1);
  }

  const today = todayShanghai();
  const pending = SEEDS.filter((s) => !fs.existsSync(path.join(FAQ_DIR, `${s.slug}.md`)));
  const todo = pending.slice(0, batch);

  console.log(`种子总数 ${SEEDS.length}，待生成 ${pending.length}，本次${dryRun ? "模拟" : "生成"} ${todo.length} 篇（batch=${batch}）`);

  for (const seed of todo) {
    const file = path.join(FAQ_DIR, `${seed.slug}.md`);
    if (dryRun) {
      console.log(`[dry-run] 将生成: ${file}`);
      continue;
    }
    fs.writeFileSync(file, renderArticle(seed, today));
    console.log(`✅ 已生成: content/articles/faq/${seed.slug}.md`);
  }

  if (dryRun) console.log("dry-run 模式：未写入任何文件");
}

main();
